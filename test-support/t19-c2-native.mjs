// Local proof adapter only. No network provider or hosted entrypoint imports this file.
import {spawn} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {createCipheriv,createDecipheriv,randomBytes,randomUUID} from 'node:crypto';
import {credentialBinding,bindingKey} from '../src/t19-c1.js';

const uuid=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const fail=code=>Object.assign(new Error(`C2 ${code}`),{code});
const quote=v=>v==null?'null':"'"+String(typeof v==='object'?JSON.stringify(v):v).replaceAll("'","''")+"'";
export function dummyBinding(value){
 const b=credentialBinding(value);
 if(b.provider!=='synthetic'||b.environment!=='synthetic'||!b.organization_id.startsWith('synthetic-'))throw fail('dummy_only');
 return b;
}
export function nativeClient(url){
 const u=new URL(url);
 if(u.hostname!=='127.0.0.1'||u.pathname!=='/faraios_t19_test'||u.password||u.search||!/^c2_worker_[ab]$/.test(u.username))throw fail('local_only');
 const sql=text=>new Promise((resolve,reject)=>{
  const p=spawn(process.env.T19_PSQL??'psql',[u.href,'-X','-qAt','-v','ON_ERROR_STOP=1','-v','VERBOSITY=verbose'],{windowsHide:true,env:{...process.env,PGOPTIONS:'-c statement_timeout=3000 -c lock_timeout=2000'}});
  let out='',err='';const timer=setTimeout(()=>p.kill(),5000);
  p.stdout.on('data',d=>out+=d);p.stderr.on('data',d=>err+=d);
  p.on('error',()=>{clearTimeout(timer);reject(fail('database_unavailable'));});
  p.on('close',code=>{clearTimeout(timer);if(code!==0)reject(fail(err.match(/ERROR:\s+([A-Z0-9]{5}):/)?.[1]??'database_unavailable'));else {try{resolve(out.trim()?JSON.parse(out):null);}catch{reject(fail('database_result'));}}});
  p.stdin.on('error',()=>{});p.stdin.end(text);
 });
 return {sql,step:(action,b,job,epoch,attempt=null,fence=null,reference=null,key=null)=>sql(`select c2.step(${[action,b,job,epoch,attempt,fence,reference,key].map(quote).join(',')});`)};
}

// Root is generated by the disposable runner. Keys here are dummy fixtures, not independent custody.
// Interface: read(binding, reference, keyVersion, epoch), seal(..., attempt), watermark(binding).
export function diskDummyCustody(root){
 const file=(id,suffix)=>{if(!uuid.test(id))throw fail('reference_rejected');return join(root,id+suffix);};
 const context=(b,key,epoch,ref)=>{dummyBinding(b);if(!Number.isSafeInteger(key)||key<1||!uuid.test(epoch)||!uuid.test(ref))throw fail('custody_rejected');return Buffer.from(JSON.stringify([bindingKey(b),key,epoch,ref]));};
 const material=m=>{if(!m||!/^dummy-[0-9a-f-]{36}$/.test(m.refresh_token))throw fail('dummy_only');return {refresh_token:m.refresh_token};};
 return {
  async seal(b,m,key,epoch,ref=randomUUID()){
   const aad=context(b,key,epoch,ref),secret=await readFile(join(root,`key-${key}`));
   const nonce=randomBytes(12),c=createCipheriv('aes-256-gcm',secret,nonce);c.setAAD(aad);
   const body=Buffer.concat([c.update(JSON.stringify(material(m))),c.final()]);
   await writeFile(file(ref,'.envelope'),JSON.stringify({nonce:nonce.toString('hex'),body:body.toString('hex'),tag:c.getAuthTag().toString('hex')}),{flag:'wx'});return ref;
  },
  async read(b,ref,key,epoch){
   try{
    const aad=context(b,key,epoch,ref),envelope=JSON.parse(await readFile(file(ref,'.envelope'),'utf8'));
    const d=createDecipheriv('aes-256-gcm',await readFile(join(root,`key-${key}`)),Buffer.from(envelope.nonce,'hex'));
    d.setAAD(aad);d.setAuthTag(Buffer.from(envelope.tag,'hex'));
    return material(JSON.parse(Buffer.concat([d.update(Buffer.from(envelope.body,'hex')),d.final()]).toString()));
   }catch{throw fail('custody_rejected');}
  },
  async watermark(b){return JSON.parse(await readFile(file(b.connection_id,'.watermark'),'utf8'));},
  async advance(b,epoch,attempt){
   // Monotonic append-only version evidence. A partial/uncertain write fails closed.
   const entry={epoch,version:b.credential_version,attempt};
   await writeFile(file(b.connection_id,`.v${b.credential_version}`),JSON.stringify(entry),{flag:'wx'});
   await writeFile(file(b.connection_id,'.watermark'),JSON.stringify(entry));
  }
 };
}

export async function runFakeRefresh({url,root,binding,job,epoch,mode='success',checkpoint=async()=>{},timeoutMs=200}){
 const b=dummyBinding(binding),db=nativeClient(url),custody=diskDummyCustody(root);
 async function checked(binding){
  const s=await db.step('current',binding,job,epoch),w=await custody.watermark(binding);
  if(w.epoch!==epoch||w.version!==binding.credential_version)throw fail('rollback_hold');
  return s;
 }
 await checked(b);const lease=await db.step('claim',b,job,epoch);
 let dispatched=false,published=false;
 try{
  await checkpoint('claimed',lease);
  await custody.read(b,lease.reference,lease.key_version,epoch);
  await checked(b);
  await db.step('dispatch',b,job,epoch,lease.attempt,lease.fence);dispatched=true;
  await checkpoint('dispatched',lease); // Durable intent committed; sending is NOT atomic with it.
  let timer;const started=performance.now();
  const result=await new Promise((resolve,reject)=>{
   timer=setTimeout(()=>reject(fail('timeout')),timeoutMs);
   if(mode!=='hang')resolve(mode==='invalid_grant'?{invalid:true}:{refresh_token:'dummy-'+randomUUID(),expires_in_ms:mode==='expired'?0:60000});
  }).finally(()=>clearTimeout(timer));
  await checkpoint('received',lease);
  if(result.invalid){await db.step('invalid_grant',b,job,epoch,lease.attempt,lease.fence);throw fail('reauthorisation_required');}
  if(result.expires_in_ms<=0)throw fail('expired_result');
  // Monotonic elapsed time; no caller clock controls the DB lease.
  const expires=started+result.expires_in_ms;
  const next=dummyBinding({...b,credential_version:b.credential_version+1});
  const ref=await custody.seal(next,result,lease.key_version,epoch,lease.attempt);
  await checkpoint('sealed',lease);
  await custody.read(next,ref,lease.key_version,epoch);
  await checked(b);
  if(performance.now()>=expires-1000)throw fail('expired_result');
  await custody.advance(next,epoch,lease.attempt);
  await checkpoint('marked',lease);
  await db.step('publish',b,job,epoch,lease.attempt,lease.fence,ref,lease.key_version);published=true;
  await checkpoint('published',lease);
  return {binding:next,attempt:lease.attempt}; // No tokens returned or logged.
 }catch(error){
  if(!published)try{await db.step(dispatched?'hold':'release',b,job,epoch,lease.attempt,lease.fence);}catch{/* DB/authority failure leaves persisted dispatch intent blocked. */}
  throw error;
 }
}
